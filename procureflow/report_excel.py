"""The three-way-match exception report, as a workbook someone can work from.

This is the artefact an AP clerk actually receives, so it is built for use
rather than for looking complete in a screenshot: filters on, header frozen,
columns wide enough to read without dragging, variance shaded by severity,
and a suggested action on every row. A report that needs reformatting before
it can be worked is a report that gets exported to CSV and done by hand.

Three sheets:

1. **Summary** — counts by exception type and the run's headline numbers.
2. **Exceptions** — one row per exception, with the rule id that produced it.
   The rule id is the column that matters: it lets the reader go from a
   number on a spreadsheet to the sentence in the policy that caused it.
3. **Run log** — every scenario, its state and what it cost.
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path
from typing import Any

from openpyxl import Workbook
from openpyxl.formatting.rule import CellIsRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.worksheet import Worksheet

INK = "1F2328"
MUTED = "59636E"
LINE = "D1D9E0"

HEAD_FILL = PatternFill("solid", fgColor=INK)
HEAD_FONT = Font(color="FFFFFF", bold=True, size=10)
TITLE_FONT = Font(bold=True, size=13, color=INK)
MUTED_FONT = Font(size=9, color=MUTED, italic=True)
THIN = Side(style="thin", color=LINE)
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

AMBER_BG, AMBER_FG = "FFF8C5", "9A6700"
RED_BG, RED_FG = "FFEBE9", "D1242F"
GREEN_BG, GREEN_FG = "DAFBE1", "1A7F37"


def _header(ws: Worksheet, row: int, headers: list[str], widths: list[int]) -> None:
    for i, (h, w) in enumerate(zip(headers, widths, strict=True), start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.fill, c.font = HEAD_FILL, HEAD_FONT
        c.alignment = Alignment(vertical="center", wrap_text=True)
        c.border = BORDER
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[row].height = 22


def _collect(rows: Iterable[Any]) -> list[dict[str, Any]]:
    """Flatten every run's exceptions into report rows.

    Scenario runs carry their exception *types*; the detail lives on the
    `MatchException` objects. Both shapes are accepted so this can be called
    from the eval harness and from a single CLI run.
    """
    out: list[dict[str, Any]] = []
    for r in rows:
        name = getattr(r, "name", None) or getattr(r, "scenario", "") or ""
        match = getattr(r, "match", None)
        if match is not None and getattr(match, "exceptions", None):
            for e in match.exceptions:
                d = e.as_row()
                d["Run"] = name
                out.append(d)
            continue
        for t in (getattr(r, "exceptions", None) or []):
            out.append({"Run": name, "Exception": t, "Rule": "", "Item": "",
                        "Purchase Order": (getattr(r, "documents", []) or [""])[0]
                        if getattr(r, "documents", None) else "",
                        "Receipt": "", "Invoice": "", "Expected": "", "Actual": "",
                        "Variance": "", "Variance %": 0.0, "Tolerance": "",
                        "Suggested action": "", "Detail": getattr(r, "reason", "")})
    return out


def _sheet_summary(wb: Workbook, exc_rows: list[dict[str, Any]],
                   summary: dict[str, Any] | None) -> None:
    ws = wb.active
    ws.title = "Summary"
    ws["A1"] = "ProcureFlow — three-way match exceptions"
    ws["A1"].font = TITLE_FONT
    ws["A2"] = ("Generated by eval/run_eval.py. Every figure below is from the run "
                "that produced this file.")
    ws["A2"].font = MUTED_FONT
    ws.column_dimensions["A"].width = 34
    ws.column_dimensions["B"].width = 18
    ws.column_dimensions["C"].width = 60

    row = 4
    _header(ws, row, ["Exception type", "Count", "What it means"], [34, 18, 60])
    meanings = {
        "price_variance": "Invoiced above the order beyond R3 (5% or ₹500, tighter).",
        "qty_short": "Less arrived than was ordered, beyond R4.",
        "qty_over": "More arrived than was ordered, beyond R4.",
        "duplicate_invoice": "This supplier invoice number is already booked (R5).",
        "missing_receipt": "Invoiced with no goods receipt. Held, not rejected (R9).",
        "possible_duplicate": "Look-alike number or same amount within 30 days (R5). Held.",
        "billed_over_received": "Billed for more than arrived, beyond R4's allowance (R11).",
        "unordered_line": "An invoice line for an item that is not on the order (R11).",
    }
    counts: dict[str, int] = {}
    for r in exc_rows:
        counts[r["Exception"]] = counts.get(r["Exception"], 0) + 1

    row += 1
    for k in sorted(meanings):
        ws.cell(row=row, column=1, value=k).border = BORDER
        c = ws.cell(row=row, column=2, value=counts.get(k, 0))
        c.border, c.alignment = BORDER, Alignment(horizontal="center")
        if counts.get(k):
            c.fill = PatternFill("solid", fgColor=AMBER_BG)
            c.font = Font(bold=True, color=AMBER_FG)
        m = ws.cell(row=row, column=3, value=meanings[k])
        m.border, m.alignment = BORDER, Alignment(wrap_text=True)
        row += 1

    ws.cell(row=row, column=1, value="Total exceptions").font = Font(bold=True)
    t = ws.cell(row=row, column=2, value=len(exc_rows))
    t.font = Font(bold=True)
    t.alignment = Alignment(horizontal="center")

    if summary:
        row += 2
        ws.cell(row=row, column=1, value="Evaluation run").font = Font(bold=True, size=11)
        row += 1
        for label, key in (("Scenarios", "scenarios"),
                           ("Task success rate", "success_rate"),
                           ("Exception-detection rate", "exception_detection_rate"),
                           ("Avg steps per run", "avg_steps"),
                           ("Latency p50 (ms)", "p50_ms"),
                           ("Latency p95 (ms)", "p95_ms"),
                           ("Mode", "mode"),
                           ("Policy retrieval", "policy_backend")):
            ws.cell(row=row, column=1, value=label).border = BORDER
            v = summary.get(key, "")
            if key.endswith("rate"):
                v = f"{v}%"
            c = ws.cell(row=row, column=2, value=v)
            c.border, c.alignment = BORDER, Alignment(horizontal="center")
            row += 1


def _sheet_exceptions(wb: Workbook, exc_rows: list[dict[str, Any]]) -> None:
    ws = wb.create_sheet("Exceptions")
    headers = ["Run", "Exception", "Rule", "Item", "Purchase Order", "Receipt",
               "Invoice", "Expected", "Actual", "Variance", "Variance %",
               "Tolerance", "Suggested action", "Detail"]
    widths = [26, 18, 7, 16, 20, 20, 20, 16, 16, 14, 12, 34, 46, 60]
    _header(ws, 1, headers, widths)

    for i, r in enumerate(exc_rows, start=2):
        for j, h in enumerate(headers, start=1):
            c = ws.cell(row=i, column=j, value=r.get(h, ""))
            c.border = BORDER
            c.alignment = Alignment(vertical="top",
                                    wrap_text=h in ("Suggested action", "Detail", "Tolerance"))
            if h == "Exception":
                c.font = Font(bold=True, color=RED_FG if r.get(h) == "duplicate_invoice"
                              else AMBER_FG)
            if h == "Rule":
                c.alignment = Alignment(horizontal="center")

    last = max(len(exc_rows) + 1, 2)
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{last}"

    # Variance shading, so the eye lands on the expensive rows first.
    col = get_column_letter(headers.index("Variance %") + 1)
    rng = f"{col}2:{col}{last}"
    ws.conditional_formatting.add(rng, CellIsRule(
        operator="greaterThanOrEqual", formula=["10"],
        fill=PatternFill("solid", fgColor=RED_BG), font=Font(color=RED_FG, bold=True)))
    ws.conditional_formatting.add(rng, CellIsRule(
        operator="between", formula=["0.001", "9.999"],
        fill=PatternFill("solid", fgColor=AMBER_BG), font=Font(color=AMBER_FG)))
    ws.conditional_formatting.add(rng, CellIsRule(
        operator="lessThan", formula=["0"],
        fill=PatternFill("solid", fgColor=GREEN_BG), font=Font(color=GREEN_FG)))
    if not exc_rows:
        ws.cell(row=2, column=1, value="No exceptions in this run.").font = MUTED_FONT


def _sheet_runlog(wb: Workbook, rows: Iterable[Any]) -> None:
    ws = wb.create_sheet("Run log")
    headers = ["Scenario", "Expected", "Actual", "Pass", "Rules cited",
               "Exceptions", "Documents", "Steps", "LLM calls", "ms", "Reason"]
    widths = [30, 24, 24, 8, 16, 22, 46, 8, 10, 8, 58]
    _header(ws, 1, headers, widths)

    for i, r in enumerate(rows, start=2):
        passed = bool(getattr(r, "passed", True))
        vals = [getattr(r, "name", ""), getattr(r, "expected_state", ""),
                getattr(r, "actual_state", ""), "yes" if passed else "NO",
                ",".join(getattr(r, "rules_cited", []) or []),
                ",".join(getattr(r, "exceptions", []) or []),
                ", ".join(getattr(r, "documents", []) or []),
                getattr(r, "steps", 0), getattr(r, "llm_calls", 0),
                getattr(r, "ms", 0), getattr(r, "reason", "")]
        for j, v in enumerate(vals, start=1):
            c = ws.cell(row=i, column=j, value=v)
            c.border = BORDER
            c.alignment = Alignment(vertical="top",
                                    wrap_text=headers[j - 1] in ("Reason", "Documents"))
            if headers[j - 1] == "Pass":
                c.alignment = Alignment(horizontal="center")
                c.font = Font(bold=True, color=GREEN_FG if passed else RED_FG)
                c.fill = PatternFill("solid", fgColor=GREEN_BG if passed else RED_BG)
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(headers))}{max(len(list(rows)) + 1, 2)}"


def write_exception_report(rows: Iterable[Any], path: str | Path, *,
                           summary: dict[str, Any] | None = None) -> int:
    """Write the workbook. Returns the number of exception rows."""
    rows = list(rows)
    exc_rows = _collect(rows)
    wb = Workbook()
    _sheet_summary(wb, exc_rows, summary)
    _sheet_exceptions(wb, exc_rows)
    _sheet_runlog(wb, rows)
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(p))
    return len(exc_rows)
